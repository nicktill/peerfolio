// Regenerates src/lib/sports/teams-data.ts (NHL, MLB, FBS college football, MLS identity tables) from ESPN's public
// site API. One-off, run by hand when a league adds/renames a team:  node scripts/generate-team-tables.mjs
// Each row is [displayName, abbr, color, altColor, logoKey, shortName]. logoKey is the file stem of ESPN's default
// logo URL (lowercase abbr for NHL/MLB, numeric id for CFB/MLS); the dark variant lives under the sibling 500-dark path.
import { writeFileSync } from "node:fs"

const API = "https://site.api.espn.com/apis"
const LEAGUES = [
  { key: "nhl", path: "hockey/nhl" },
  { key: "mlb", path: "baseball/mlb" },
  { key: "cfb", path: "football/college-football", fbs: true },
  { key: "mls", path: "soccer/usa.1" },
]

const getJson = async (url) => (await fetch(url)).json()
const hex = (c) => (c && /^[0-9a-f]{6}$/i.test(c) ? `#${c.toLowerCase()}` : "")

async function fbsIds() {
  const j = await getJson(`${API}/v2/sports/football/college-football/standings?group=80`)
  const ids = new Set()
  const walk = (n) => {
    for (const e of n.standings?.entries ?? []) ids.add(String(e.team.id))
    for (const c of n.children ?? []) walk(c)
  }
  walk(j)
  return ids
}

const out = {}
for (const lg of LEAGUES) {
  const only = lg.fbs ? await fbsIds() : null
  // The teams endpoint caps a page (college football has ~700 teams incl. FCS/D2), so page until empty.
  const teams = []
  for (let page = 1; page < 10; page++) {
    const j = await getJson(`${API}/site/v2/sports/${lg.path}/teams?limit=200&page=${page}`)
    const batch = j.sports[0].leagues[0].teams
    if (!batch.length) break
    teams.push(...batch)
    if (batch.length < 200) break
  }
  const rows = []
  for (const { team: t } of teams) {
    if (only && !only.has(String(t.id))) continue
    const href = t.logos?.find((l) => l.rel?.includes("default"))?.href ?? ""
    const stem = href.split("/").pop()?.replace(/\.png$/, "") ?? ""
    rows.push([t.displayName, t.abbreviation, hex(t.color), hex(t.alternateColor), stem, t.shortDisplayName ?? ""])
  }
  rows.sort((a, b) => a[0].localeCompare(b[0]))
  out[lg.key] = rows
}

const body = Object.entries(out)
  .map(([k, rows]) => `export const ${k.toUpperCase()}_TEAMS: TeamRow[] = [\n${rows.map((r) => `  ${JSON.stringify(r)},`).join("\n")}\n]`)
  .join("\n\n")
writeFileSync(
  new URL("../src/lib/sports/teams-data.ts", import.meta.url),
  `// GENERATED by scripts/generate-team-tables.mjs from ESPN's public teams API. Do not hand-edit.\n/** [displayName, abbr, color, altColor, logoKey, shortName] */\nexport type TeamRow = [string, string, string, string, string, string]\n\n${body}\n`,
)
